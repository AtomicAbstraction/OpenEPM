ALTER TABLE epm.rollup_placement_path_edge ENABLE ROW LEVEL SECURITY;
CREATE POLICY rollup_placement_path_scope ON epm.rollup_placement_path TO epm_runtime
 USING(workspace_id=current_setting('epm.workspace_id',true)
   AND application_id=current_setting('epm.application_id',true))
 WITH CHECK(workspace_id=current_setting('epm.workspace_id',true)
   AND application_id=current_setting('epm.application_id',true));
CREATE POLICY rollup_placement_path_edge_scope ON epm.rollup_placement_path_edge TO epm_runtime
 USING(workspace_id=current_setting('epm.workspace_id',true)
   AND application_id=current_setting('epm.application_id',true))
 WITH CHECK(workspace_id=current_setting('epm.workspace_id',true)
   AND application_id=current_setting('epm.application_id',true));
CREATE POLICY rollup_placement_path_lifecycle ON epm.rollup_placement_path TO epm_lifecycle
 USING(current_setting('epm.lifecycle_context',true)='workspace_reset');
CREATE POLICY rollup_placement_path_edge_lifecycle ON epm.rollup_placement_path_edge TO epm_lifecycle
 USING(current_setting('epm.lifecycle_context',true)='workspace_reset');

