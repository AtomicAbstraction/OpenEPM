CREATE TABLE epm.rollup_placement_path(
 workspace_id text NOT NULL, application_id text NOT NULL,
 generation_id text NOT NULL, coordinate_id bigint NOT NULL,
 placement_path_id text NOT NULL CHECK(placement_path_id~'^[0-9a-f]{64}$'),
 path_ordinal integer NOT NULL CHECK(path_ordinal BETWEEN 1 AND 100),
 hierarchy_dimension_id text NOT NULL, hierarchy_version bigint NOT NULL,
 root_member_id text NOT NULL, leaf_member_id text NOT NULL,
 relationship_count integer NOT NULL CHECK(relationship_count BETWEEN 1 AND 32),
 PRIMARY KEY(workspace_id,application_id,generation_id,coordinate_id,placement_path_id),
 UNIQUE(workspace_id,application_id,generation_id,coordinate_id,
        placement_path_id,path_ordinal),
 UNIQUE(workspace_id,application_id,generation_id,coordinate_id,path_ordinal),
 FOREIGN KEY(workspace_id,application_id,generation_id,coordinate_id)
  REFERENCES epm.calculation_result(workspace_id,application_id,generation_id,coordinate_id)
  ON DELETE RESTRICT,
 FOREIGN KEY(workspace_id,application_id,hierarchy_dimension_id,hierarchy_version)
  REFERENCES epm.hierarchy_version(workspace_id,application_id,dimension_id,version)
  ON DELETE RESTRICT,
 FOREIGN KEY(workspace_id,application_id,hierarchy_dimension_id,root_member_id)
  REFERENCES epm.member(workspace_id,application_id,dimension_id,member_id)
  ON DELETE RESTRICT,
 FOREIGN KEY(workspace_id,application_id,hierarchy_dimension_id,leaf_member_id)
  REFERENCES epm.member(workspace_id,application_id,dimension_id,member_id)
  ON DELETE RESTRICT);

ALTER TABLE epm.relationship ADD CONSTRAINT relationship_identity_snapshot_unique
 UNIQUE(workspace_id,application_id,relationship_id,dimension_id,
        parent_member_id,child_member_id);

CREATE TABLE epm.rollup_placement_path_edge(
 workspace_id text NOT NULL, application_id text NOT NULL,
 generation_id text NOT NULL, coordinate_id bigint NOT NULL,
 placement_path_id text NOT NULL, edge_ordinal integer NOT NULL CHECK(edge_ordinal BETWEEN 1 AND 32),
 relationship_id text NOT NULL, hierarchy_dimension_id text NOT NULL,
 parent_member_id text NOT NULL, child_member_id text NOT NULL,
 PRIMARY KEY(workspace_id,application_id,generation_id,coordinate_id,placement_path_id,edge_ordinal),
 FOREIGN KEY(workspace_id,application_id,generation_id,coordinate_id,placement_path_id)
  REFERENCES epm.rollup_placement_path
  (workspace_id,application_id,generation_id,coordinate_id,placement_path_id)
  ON DELETE RESTRICT,
 FOREIGN KEY(workspace_id,application_id,relationship_id,hierarchy_dimension_id,
             parent_member_id,child_member_id)
  REFERENCES epm.relationship(workspace_id,application_id,relationship_id,
             dimension_id,parent_member_id,child_member_id)
  ON DELETE RESTRICT);

ALTER TABLE epm.rollup_source_lineage DROP CONSTRAINT rollup_source_lineage_pkey;
ALTER TABLE epm.rollup_source_lineage
 ADD COLUMN lineage_ordinal bigint GENERATED BY DEFAULT AS IDENTITY,
 ADD COLUMN placement_path_id text,
 ADD COLUMN placement_path_ordinal integer,
 ADD CONSTRAINT rollup_source_lineage_pkey PRIMARY KEY
  (workspace_id,application_id,generation_id,coordinate_id,lineage_ordinal),
 ADD CONSTRAINT rollup_source_path_shape CHECK(
  (placement_path_id IS NULL AND placement_path_ordinal IS NULL)
  OR (source_selection='hierarchy' AND placement_path_id~'^[0-9a-f]{64}$'
      AND placement_path_ordinal BETWEEN 1 AND 100)),
 ADD CONSTRAINT rollup_source_path_fk FOREIGN KEY
  (workspace_id,application_id,generation_id,coordinate_id,
   placement_path_id,placement_path_ordinal)
  REFERENCES epm.rollup_placement_path
  (workspace_id,application_id,generation_id,coordinate_id,
   placement_path_id,path_ordinal)
  ON DELETE RESTRICT;
CREATE UNIQUE INDEX rollup_source_legacy_unique ON epm.rollup_source_lineage
 (workspace_id,application_id,generation_id,coordinate_id,source_coordinate_id)
 WHERE placement_path_id IS NULL;
CREATE UNIQUE INDEX rollup_source_path_unique ON epm.rollup_source_lineage
 (workspace_id,application_id,generation_id,coordinate_id,placement_path_id,source_coordinate_id)
 WHERE placement_path_id IS NOT NULL;
CREATE INDEX rollup_path_leaf ON epm.rollup_placement_path
 (workspace_id,application_id,leaf_member_id,generation_id);
CREATE INDEX rollup_path_edge_relationship ON epm.rollup_placement_path_edge
 (workspace_id,application_id,relationship_id,generation_id);
GRANT USAGE,SELECT ON SEQUENCE epm.rollup_source_lineage_lineage_ordinal_seq TO epm_runtime;

REVOKE ALL ON epm.rollup_placement_path,epm.rollup_placement_path_edge
 FROM PUBLIC,epm_runtime,epm_worker,epm_analyst,epm_lifecycle;
GRANT SELECT,INSERT ON epm.rollup_placement_path,epm.rollup_placement_path_edge TO epm_runtime;
GRANT DELETE ON epm.rollup_placement_path_edge,epm.rollup_placement_path TO epm_lifecycle;
