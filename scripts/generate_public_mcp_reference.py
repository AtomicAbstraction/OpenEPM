ROOT = Path(__file__).resolve().parents[1]
PAGES = ROOT / "public-landing/documentation/pages"
INVENTORY = ROOT / "docs/public-documentation-mcp-inventory.json"
CONTENT = ROOT / "docs/public-documentation-mcp-reference-content.json"
ENDPOINT_LABELS = {
    "platform": "Platform",
    "workspace": "Bound workspace",
    "application-bound": "Bound application",
    "application-router": "Application router",
    "reset-apply": "Dedicated reset apply",
}


def tool_slug(name):
    return "mcp-reference-" + name.replace("_", "-")


def route_link(slug, label):
    return f'<a href="/documentation/{slug}/">{escape(label)}</a>'


def json_block(value, kind):
    content = escape(json.dumps(value, ensure_ascii=False, indent=2))
    return f'<pre><code data-contract="{kind}">{content}</code></pre>'


def provenance(paths):
    digest = hashlib.sha256()
    for path in sorted(set(paths)):
        digest.update(path.relative_to(ROOT).as_posix().encode() + b"\0")
        digest.update(hashlib.sha256(path.read_bytes()).digest())
    generator = Path(__file__).resolve().relative_to(ROOT)
    return f"<!-- Generated by {generator}; source SHA-256 {digest.hexdigest()}. -->"


def verify_inventory_sources(inventory):
    stale = []
    for entry in inventory["sourceState"]["files"]:
        path = ROOT / entry["path"]
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != entry["sha256"]:
            stale.append(entry["path"])
    if stale:
        raise ValueError(f"Review and refresh the MCP inventory source hashes for {stale}")


async def discover(inventory):
    variants = {}
    for endpoint in inventory["endpoints"]:
        server = importlib.import_module(endpoint["source"].removesuffix(".py")).server
        tools = await server.list_tools()
        resources = await server.list_resources()
        counts = {
            "registeredToolCount": len(tools),
            "registeredPromptCount": len(await server.list_prompts()),
            "registeredResourceCount": len(resources),
            "registeredResourceTemplateCount": len(await server.list_resource_templates()),
        }
        if any(count != endpoint[key] for key, count in counts.items()):
            raise ValueError(f"MCP discovery counts changed for {endpoint['id']}: {counts}")
        if sorted(str(resource.uri) for resource in resources) != endpoint["registeredResourceUris"]:
            raise ValueError(f"MCP resource identities changed for {endpoint['id']}")
        for tool in tools:
            variants[endpoint["id"], tool.name] = (tool.description, tool.input_schema)
    recorded = {
        (variant["endpoint"], tool["name"]): (variant["description"], variant["inputSchema"])
        for tool in inventory["tools"] for variant in tool["variants"]
    }
    if variants != recorded:
        changed = sorted(key for key in variants.keys() | recorded.keys()
                         if variants.get(key) != recorded.get(key))
        raise ValueError(f"Refresh the reviewed MCP discovery inventory for {changed}")
    return variants


def public_catalogs():
    from epm_core.postgres_capability_contract import KNOWN_CAPABILITIES, filter_catalog
    from epm_core.postgres_identity_directory import catalog as directory_catalog
    from epm_core.postgres_language_v2 import PostgresLanguageV2
    from epm_core.postgres_platform_provision import PostgresPlatformProvisioner
    from epm_core.postgres_security_language import PostgresSecurityLanguage
    from epm_core.processing_operation_registry import external_function_catalog, operation_contracts

    app = filter_catalog(PostgresLanguageV2.catalog(), KNOWN_CAPABILITIES)["functions"]
    security = PostgresSecurityLanguage.catalog()["functions"]
    workspace = external_function_catalog()
    reset = {"workspace.reset.apply": workspace.pop("workspace.reset.apply")}
    platform = {
        **PostgresPlatformProvisioner.catalog()["functions"],
        **directory_catalog()["functions"],
    }
    application = with_mcp_tools({**app, **security}, scope='application')
    workspace = with_mcp_tools(workspace, scope='workspace')
    reset = with_mcp_tools(reset, scope='workspace')
    platform = with_mcp_tools(platform, scope='platform')
    operations = {
        **operation_contracts(application, scope="application"),
        **operation_contracts({**workspace, **reset}, scope="workspace"),
        **operation_contracts(platform, scope="platform"),
    }
    return application, security, workspace, reset, platform, operations


def tool_page(tool, content, discovery, dispatch):
    from epm_core.postgres_execution_policy import CAPACITY_CODE, DEADLINE_CODE, FAILURE_CODE

    name = tool["name"]
    example = content["example"]
    if "program" in example:
        program = example["program"]
        if (set(program) != {"languageVersion", "function", "arguments"}
                or program["languageVersion"] != 2
                or name not in dispatch.get(program["function"], ())
                or not isinstance(program["arguments"], dict)):
            raise ValueError(f"Invalid documented program for {name}")
    module = tool["functionalityModule"]
    origins = [ROOT / item["source"] for item in tool["variants"]]
    origins.append(ROOT / "epm_core/postgres_execution_policy.py")
    blocks = [
        provenance([Path(__file__).resolve(), ROOT / 'epm_core/mcp_function_routing.py', INVENTORY, CONTENT, *origins]),
        f'<p>{escape(content["usage"])}</p>',
        '<p>These signatures come from local MCP tool discovery. Use the '
        'signature registered by your deployment and confirm your identity '
        'and permissions before calling the tool.</p>',
        '<h2>Endpoint signatures and example arguments</h2>',
        '<p>Examples show the arguments to the tool. Replace placeholder IDs '
        'and illustrative revisions with values from your authorized disposable scope.</p>',
    ]
    for variant in tool["variants"]:
        endpoint = variant["endpoint"]
        description, schema = discovery[endpoint, name]
        required = schema.get("required", [])
        optional = [key for key in schema["properties"] if key not in required]
        arguments = {
            key: value for key, value in {
                "workspace_id": "{{workspace_id}}", "application_id": "operating-cube",
            }.items() if key in schema["properties"]
        } | example
        if set(arguments) - schema["properties"].keys():
            raise ValueError(f"Unknown example arguments for {endpoint} {name}")
        Draft202012Validator.check_schema(schema)
        Draft202012Validator(schema).validate(arguments)
        arg_list = lambda keys: ", ".join(f"<code>{escape(key)}</code>" for key in keys) or "None"
        blocks.extend((
            f'<section data-endpoint="{endpoint}">',
            f'<h3>{ENDPOINT_LABELS[endpoint]}</h3>',
            f'<p>{escape(description)}</p>',
            f'<dl><dt>Required arguments</dt><dd>{arg_list(required)}</dd>'
            f'<dt>Optional arguments</dt><dd>{arg_list(optional)}</dd></dl>',
            json_block(arguments, "tool-example"),
            '<details><summary>Exact JSON input schema</summary>',
            json_block(schema, "tool-input-schema"),
            '</details></section>',
        ))
    tool_functions = [function for function, names in sorted(dispatch.items()) if name in names]
    if tool_functions:
        blocks.append("<details><summary>Supported application-language functions</summary><ul>")
        for function in tool_functions:
            blocks.append(f'<li><a href="/documentation/mcp-function-catalog/#{function}">'
                          f'<code>{escape(function)}</code></a></li>')
        blocks.append("</ul></details>")
    recovery = route_link("mcp-recover-outcome", "reconcile the original request")
    blocks.extend((
        "<h2>Handling errors</h2>",
        f"<p><code>{CAPACITY_CODE}</code> means the server did not dispatch this "
        f"call. <code>{DEADLINE_CODE}</code> or <code>{FAILURE_CODE}</code> leaves "
        f"the outcome unknown. For a call with effects, {recovery} before "
        "starting a new one. For a scoped denial, verify the caller's grant "
        "and the selected target.</p>",
    ))
    related = route_link(content["relatedPage"], "Related workflow")
    catalog = route_link("mcp-function-catalog", "Application-language function catalog")
    guidelines = route_link(f"mcp-guide-{module}", "Module guidelines")
    related_links = dict.fromkeys((guidelines, related, catalog))
    if content["relatedPage"] == f"mcp-guide-{module}":
        del related_links[related]
    blocks.append(f"<p>{' · '.join(related_links)}</p>")
    return "\n".join(blocks) + "\n"


def catalog_page(scopes, operations, dispatch, security):
    origins = [
        ROOT / path for path in (
            "epm_core/postgres_platform_provision.py",
            "epm_core/postgres_identity_directory.py",
            "epm_core/postgres_language_v2.py",
            "epm_core/postgres_operation_receipts.py",
            "epm_core/postgres_capability_contract.py",
            "epm_core/postgres_security_language.py",
            "epm_core/postgres_workspace_lifecycle.py",
            "epm_core/postgres_workspace_reset.py",
            "epm_core/postgres_workspace_reset_apply.py",
            "epm_core/processing_operation_registry.py",
        )
    ]
    blocks = [
        provenance([Path(__file__).resolve(), ROOT / 'epm_core/mcp_function_routing.py', CONTENT, INVENTORY, *origins]),
        '<p>Application-language functions are selected by <code>program.function</code> '
        'inside a callable MCP tool. The tables below show contracts extracted from '
        'the current local code.</p>',
        '<p>Use authenticated discovery for the actual deployment, role and scope. '
        'Application discovery is filtered by current grants and capabilities. '
        'Security functions additionally require the configured security service. '
        'Some functions require other deployment services such as a Python build runtime.</p>',
    ]
    for scope_id, label, functions, discovery_tool in scopes:
        blocks.append(f'<h2 id="{scope_id}">{label}</h2>')
        if discovery_tool:
            blocks.append(f'<p>Discover with {route_link(tool_slug(discovery_tool), discovery_tool)}.</p>')
        blocks.append(f'<p>{len(functions)} functions in this local catalog.</p>')
        for name, specification in sorted(functions.items()):
            display_spec = {key: value for key, value in specification.items()
                            if not key.startswith("_") and key != "privateCompatibilitySource"}
            blocks.append(f'<details id="{name}" data-function-scope="{scope_id}">'
                          f'<summary><code>{escape(name)}</code></summary>')
            if name in security:
                blocks.append('<p>Requires the configured application security service.</p>')
            links = ", ".join(route_link(tool_slug(tool), tool) for tool in dispatch[name])
            blocks.append(f'<p>Tool reference · {links}</p>')
            blocks.append(json_block(display_spec, "function-specification"))
            if name in operations:
                blocks.append(json_block(operations[name]["replay"], "function-replay"))
            blocks.append("</details>")
    return "\n".join(blocks) + "\n"


async def generate(check):
    inventory = json.loads(INVENTORY.read_text())
    verify_inventory_sources(inventory)
    content = json.loads(CONTENT.read_text())
    tool_names = {tool["name"] for tool in inventory["tools"]}
    if tool_names != content.keys():
        raise ValueError("Tool reference content must cover every discovered name exactly once")
    discovery = await discover(inventory)
    application, security, workspace, reset, platform, operations = public_catalogs()
    functions = {**application, **workspace, **reset, **platform}
    dispatch = public_dispatch(application, workspace, reset, platform)
    if not {tool for names in dispatch.values() for tool in names} <= tool_names:
        raise ValueError("Function index refers to a tool absent from public discovery")
    scopes = (
        ("application-functions", "Application functions", application, "list_v2_functions"),
        ("workspace-functions", "Workspace functions", workspace, "list_v2_workspace_functions"),
        ("platform-functions", "Platform functions", platform, "list_v2_platform_functions"),
        ("reset-functions", "Dedicated reset function", reset, None),
    )
    generated = {
        PAGES / f'{tool_slug(tool["name"])}.html':
            tool_page(tool, content[tool["name"]], discovery, dispatch)
        for tool in inventory["tools"]
    }
    generated[PAGES / "mcp-function-catalog.html"] = catalog_page(
        scopes, operations, dispatch, security)
    for path, body in generated.items():
        if check:
            if not path.is_file() or path.read_text() != body:
                raise ValueError(f"Stale generated reference {path.relative_to(ROOT)}")
        else:
            path.write_text(body, encoding="utf-8")
    print(f"{len(tool_names)} tools, {len(discovery)} endpoint signatures and "
          f"{len(functions)} scoped functions")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify without rewriting pages")
    args = parser.parse_args()
    sys.path.insert(0, str(ROOT))
    asyncio.run(generate(args.check))
